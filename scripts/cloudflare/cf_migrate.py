#!/usr/bin/env python3
"""Prepare a jabbitapp.com checkout for Cloudflare and hand the peptide/longevity pages to millenaut.com.

usage: cf_migrate.py JABBIT_CHECKOUT
Re-runnable: run it again after merging main to catch pages added since.
"""
import json
import pathlib
import re
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import move_list  # noqa: E402

ROOT = pathlib.Path(sys.argv[1]).resolve()
MILLENAUT = "https://millenaut.com"

research, peptides = move_list.moved(ROOT)
research = [r for r in research if r != "index"]
MOVED = {f"/research/{r}.html": f"{MILLENAUT}/research/{r}.html" for r in research}
MOVED.update({f"/peptides/{p}.html": f"{MILLENAUT}/peptides/{p}.html" for p in peptides if p != "index"})
for src in ("/peptides", "/peptides/", "/peptides/index.html"):
    MOVED[src] = f"{MILLENAUT}/peptides"
for src in ("/peptide-reconstitution-calculator", "/peptide-reconstitution-calculator/",
            "/peptide-reconstitution-calculator.html", "/peptide-reconstitution-calculator/index.html"):
    MOVED[src] = f"{MILLENAUT}/peptide-reconstitution-calculator"


def moved_target(url):
    path = url.split("#")[0].split("?")[0]
    if path.startswith("https://jabbitapp.com"):
        path = path[len("https://jabbitapp.com"):] or "/"
    return MOVED.get(path)


# 1. Redirects: Vercel's list keeps working for the transition; Cloudflare reads _redirects.
vercel = json.loads((ROOT / "vercel.json").read_text())
old = [r for r in vercel["redirects"] if r["source"] not in MOVED]
for r in old:
    r["destination"] = moved_target(r["destination"]) or r["destination"]
new = [{"source": s, "destination": d, "permanent": True} for s, d in sorted(MOVED.items())]
vercel["redirects"] = new + old
(ROOT / "vercel.json").write_text(json.dumps(vercel, indent=2) + "\n")

lines = ["# Generated by cf_migrate.py from vercel.json (Cloudflare Workers static assets format).",
         "# Peptide and longevity pages moved to millenaut.com on 2026-10-28."]
for r in vercel["redirects"]:
    status = 301 if r["destination"].startswith(MILLENAUT) else (308 if r.get("permanent") else 307)
    lines.append(f'{r["source"]} {r["destination"]} {status}')
(ROOT / "_redirects").write_text("\n".join(lines) + "\n")

headers = ["/*", "  X-Content-Type-Options: nosniff", "  Referrer-Policy: strict-origin-when-cross-origin",
           "  X-Frame-Options: SAMEORIGIN", "  Permissions-Policy: camera=(), microphone=(), geolocation=()", "",
           "/images/*", "  Cache-Control: public, max-age=604800, stale-while-revalidate=86400", "",
           "/assets/*", "  Cache-Control: public, max-age=86400, stale-while-revalidate=604800", ""]
for icon in ("favicon.ico", "favicon-32x32.png", "apple-touch-icon.png", "icon-192.png", "icon-512.png"):
    headers += [f"/{icon}", "  Cache-Control: public, max-age=604800", ""]
(ROOT / "_headers").write_text("\n".join(headers))

# 2. Remove the moved pages.
to_remove = [f"research/{r}.html" for r in research] + [f"peptides/{p}.html" for p in peptides]
to_remove += ["peptide-reconstitution-calculator.html", "peptide-reconstitution-calculator"]
existing = [p for p in to_remove if (ROOT / p).exists()]
if existing:
    subprocess.run(["git", "-C", str(ROOT), "rm", "-r", "-q", "--", *existing], check=True)

# 3. Links in the pages that stay.
has_ivf = (ROOT / "ivf/index.html").exists()
nav_new = '<a href="/ivf">IVF</a>' if has_ivf else ""
changed = 0
for page in ROOT.rglob("*.html"):
    rel = page.relative_to(ROOT).as_posix()
    if rel.startswith(("node_modules/", "output/", "docs/", "scripts/", ".git/")):
        continue
    t = original = page.read_text()
    t = t.replace('<a href="/peptides">Peptides</a>', nav_new)
    if rel.startswith("peptides/"):
        t = re.sub(r'<a href="/peptides/?">Peptides</a>', '<a href="/glp1">GLP-1</a>', t)
    if rel == "research/index.html":
        # The hub lists only what lives here now.
        t = re.sub(r'<a class="card" href="(/research/[^"]+)"[\s\S]*?</a>\s*',
                   lambda m: "" if m.group(1) in MOVED else m.group(0), t)
    t = re.sub(r'\b(href|src)="([^"]+)"',
               lambda m: f'{m.group(1)}="{moved_target(m.group(2)) or m.group(2)}"'
               if not m.group(2).startswith(MILLENAUT) else m.group(0), t)
    if t != original:
        page.write_text(t)
        changed += 1

# 4. Sitemap and llms.txt list only pages that live here.
moved_urls = {"https://jabbitapp.com" + s for s in MOVED}
sitemap = (ROOT / "sitemap.xml").read_text()
sitemap = re.sub(r"\s*<url>\s*<loc>([^<]+)</loc>[\s\S]*?</url>",
                 lambda m: "" if m.group(1).rstrip("/") in moved_urls or m.group(1) in moved_urls else m.group(0), sitemap)
(ROOT / "sitemap.xml").write_text(sitemap)
llms = (ROOT / "llms.txt").read_text().splitlines()
(ROOT / "llms.txt").write_text("\n".join(l for l in llms if not any(u in l for u in moved_urls)) + "\n")

print(f"{len(MOVED)} redirects to millenaut.com; removed {len(existing)} paths; rewrote {changed} pages; "
      f"nav link {'-> /ivf' if has_ivf else 'removed'}")
